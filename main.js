const esText = {};
const esAria = {};

document.querySelectorAll("[data-i18n]").forEach((el) => {
  esText[el.dataset.i18n] = el.textContent.trim();
});

document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
  esAria[el.dataset.i18nAria] = el.getAttribute("aria-label");
});

esText["meta.title"] = document.title;
esText["meta.description"] = document.querySelector('meta[name="description"]').content;

const meta = {
  description: document.querySelector('meta[name="description"]'),
  ogTitle: document.querySelector('meta[property="og:title"]'),
  ogDescription: document.querySelector('meta[property="og:description"]')
};

function readLang() {
  try {
    return localStorage.getItem("portfolio-lang") === "en" ? "en" : "es";
  } catch (error) {
    return "es";
  }
}

let lang = readLang();

function copy(key) {
  return lang === "en" ? en[key] : esText[key];
}

const esAriaExtras = {
  "nav.close": "Cerrar menú"
};

function ariaCopy(key) {
  if (lang === "en") return en[key];
  return esAria[key] || esAriaExtras[key];
}

function applyLanguage() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = copy(el.dataset.i18n);
    if (value) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = ariaCopy(el.dataset.i18nAria);
    if (value) el.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", button.dataset.setLang === lang ? "true" : "false");
  });
  document.title = copy("meta.title");
  meta.description.setAttribute("content", copy("meta.description"));
  meta.ogTitle.setAttribute("content", copy("meta.title"));
  meta.ogDescription.setAttribute("content", copy("meta.description"));
  const toggle = document.querySelector(".nav-toggle");
  if (toggle) {
    const open = toggle.getAttribute("aria-expanded") === "true";
    toggle.dataset.i18nAria = open ? "nav.close" : "nav.open";
    toggle.setAttribute("aria-label", ariaCopy(toggle.dataset.i18nAria));
  }
}

function setLang(next) {
  lang = next === "en" ? "en" : "es";
  try {
    localStorage.setItem("portfolio-lang", lang);
  } catch (error) {
    /* ignore private mode */
  }
  applyLanguage();
}

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => setLang(button.dataset.setLang));
});

const nav = document.getElementById("site-nav");
const toggle = document.querySelector(".nav-toggle");

function setMenu(open) {
  nav.classList.toggle("is-open", open);
  toggle.setAttribute("aria-expanded", open ? "true" : "false");
  toggle.dataset.i18nAria = open ? "nav.close" : "nav.open";
  toggle.setAttribute("aria-label", ariaCopy(toggle.dataset.i18nAria));
}

toggle.addEventListener("click", () => {
  setMenu(toggle.getAttribute("aria-expanded") !== "true");
});

nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => setMenu(false));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});

const header = document.querySelector(".site-header");
const onScroll = () => header.classList.toggle("is-scrolled", window.scrollY > 8);
onScroll();
window.addEventListener("scroll", onScroll, { passive: true });

const navLinks = [...nav.querySelectorAll("a")];
const sections = navLinks
  .map((link) => document.querySelector(link.getAttribute("href")))
  .filter(Boolean);

const spy = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    navLinks.forEach((link) => {
      link.classList.toggle("is-current", link.getAttribute("href") === `#${entry.target.id}`);
    });
  });
}, { rootMargin: "-45% 0px -48% 0px" });

sections.forEach((section) => spy.observe(section));

const filters = [...document.querySelectorAll("[data-filter]")];
const projects = [...document.querySelectorAll(".project")];

function applyFilter(name) {
  filters.forEach((button) => {
    button.setAttribute("aria-pressed", button.dataset.filter === name ? "true" : "false");
  });
  projects.forEach((project) => {
    const tags = project.dataset.tags.split(/\s+/);
    const show = name === "all"
      || tags.includes(name)
      || (name === "enterprise" && (tags.includes("csharp") || tags.includes("sap")));
    project.hidden = !show;
  });
}

filters.forEach((button) => {
  button.addEventListener("click", () => applyFilter(button.dataset.filter));
});

